/// ذكر واحد: إما نص مكتوب، أو آيات تُقرأ من حزمة المصحف (لتفادي أي خطأ في النسخ)
class Dhikr {
  const Dhikr(this.text, {this.count = 1, this.title})
      : surah = null,
        from = null,
        to = null;

  const Dhikr.quran(this.title, this.surah, this.from, this.to,
      {this.count = 1})
      : text = null;

  final String? text;
  final String? title;
  final int? surah;
  final int? from;
  final int? to;
  final int count;

  String get body {
    if (text != null) return text!;
    final verses = <String>[];
    for (var a = from!; a <= to!; a++) {
      verses.add(quran.getVerse(surah!, a, verseEndSymbol: true));
    }
    return verses.join(' ');
  }
}

class DhikrCategory {
  const DhikrCategory(this.name, this.hint, this.icon, this.items);

  final String name;
  final String hint;
  final FaIconData icon;
  final List<Dhikr> items;
}

